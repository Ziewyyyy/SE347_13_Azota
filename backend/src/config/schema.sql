CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE TABLE IF NOT EXISTS users (
  "userId" VARCHAR(50) PRIMARY KEY DEFAULT uuid_generate_v4(),
  "email" VARCHAR(255) UNIQUE NOT NULL,
  "passwordHash" VARCHAR(255) NOT NULL,
  "fullName" VARCHAR(100) NOT NULL,
  "avatarUrl" VARCHAR(500),
  "role" VARCHAR(20) NOT NULL CHECK ("role" IN ('STUDENT', 'TEACHER', 'ADMIN')),
  "status" VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK ("status" IN ('ACTIVE', 'LOCKED', 'DISABLED')),
  "createdAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS students (
  "studentId" VARCHAR(50) PRIMARY KEY DEFAULT uuid_generate_v4(),
  "userId" VARCHAR(50) NOT NULL UNIQUE REFERENCES users("userId") ON DELETE CASCADE,
  "studentCode" VARCHAR(50),
  "faculty" VARCHAR(100),
  "major" VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS teachers (
  "teacherId" VARCHAR(50) PRIMARY KEY DEFAULT uuid_generate_v4(),
  "userId" VARCHAR(50) NOT NULL UNIQUE REFERENCES users("userId") ON DELETE CASCADE,
  "teacherCode" VARCHAR(50),
  "faculty" VARCHAR(100),
  "department" VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  "resetTokenId" VARCHAR(50) PRIMARY KEY DEFAULT uuid_generate_v4(),
  "userId" VARCHAR(50) NOT NULL REFERENCES users("userId") ON DELETE CASCADE,
  "token" VARCHAR(255) UNIQUE,
  "otpCode" VARCHAR(10),
  "expiresAt" TIMESTAMP WITH TIME ZONE NOT NULL,
  "usedAt" TIMESTAMP WITH TIME ZONE,
  "createdAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_sessions (
  "sessionId" VARCHAR(50) PRIMARY KEY DEFAULT uuid_generate_v4(),
  "userId" VARCHAR(50) NOT NULL REFERENCES users("userId") ON DELETE CASCADE,
  "refreshTokenHash" TEXT NOT NULL UNIQUE,
  "expiresAt" TIMESTAMP WITH TIME ZONE NOT NULL,
  "revokedAt" TIMESTAMP WITH TIME ZONE,
  "createdAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS registration_otps (
  "email" VARCHAR(255) PRIMARY KEY,
  "otpCode" VARCHAR(10) NOT NULL,
  "expiresAt" TIMESTAMP WITH TIME ZONE NOT NULL,
  "createdAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);